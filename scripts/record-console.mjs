// Optional local browser verification. PLAYWRIGHT_MODULE may point to an installed copy.
import { mkdirSync, writeFileSync } from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true })
const results = []
mkdirSync('docs/media/console-frames', { recursive: true })
try {
  for (const [width, height] of [[1440, 900], [430, 932], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' })
    await page.goto('http://127.0.0.1:4317')
    await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await page.getByText('Memory starts with a decision.').waitFor()
    await page.keyboard.press('Tab')
    await page.evaluate(() => scrollTo(0, 0))
    if (width === 1440) await page.screenshot({ path: 'docs/media/console-frames/00.png' })
    for (let i = 1; i <= 3; i++) {
      await page.getByRole('button', { name: 'Next write' }).click()
      await page.waitForFunction(i => document.getElementById('attempted').textContent === String(i).padStart(2, '0'), i)
      await page.evaluate(() => scrollTo(0, 0))
    if (width === 1440) await page.screenshot({ path: `docs/media/console-frames/0${i}.png` })
    }
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: `docs/media/write-gate-light-${width}x${height}.png` })
    await page.getByRole('button', { name: 'Approve' }).click()
    await page.getByText('approved and screened again').waitFor()
    await page.evaluate(() => scrollTo(0, 0))
    if (width === 1440) await page.screenshot({ path: 'docs/media/console-frames/04.png' })
    for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Next write' }).click()
    await page.getByRole('button', { name: 'Reject', exact: true }).click()
    await page.getByRole('tab', { name: 'Red-team lab' }).click()
    await page.getByRole('heading', { name: 'Instruction injection', exact: true }).last().waitFor()
    await page.getByRole('button', { name: 'Replay red-team cases' }).click()
    await page.getByText('untrusted-source', { exact: true }).last().waitFor()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    if (overflow) throw new Error(`Overflow at ${width}`)
    const undersized = await page.locator('button:visible').evaluateAll(els => els.filter(el => { const r = el.getBoundingClientRect()
      return r.width < 43.99 || r.height < 43.99 }).map(el => ({text:el.textContent, width:el.getBoundingClientRect().width, height:el.getBoundingClientRect().height})))
    if (undersized.length) throw new Error(`Small targets at ${width}: ${JSON.stringify(undersized)}`)
    await page.getByRole('tab', { name: 'Red-team lab' }).focus()
    await page.keyboard.press('ArrowLeft')
    if (await page.getByRole('tab', { name: 'Audit log' }).getAttribute('aria-selected') !== 'true') throw new Error('Keyboard tab failed')
    await page.getByRole('button', { name: 'Switch color theme' }).click()
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: `docs/media/write-gate-dark-${width}x${height}.png` })
    await page.route('**/api/next', route => route.fulfill({ status: 500, body: '{}' }))
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await page.getByRole('button', { name: 'Next write' }).click()
    await page.getByRole('alert').waitFor()
    await page.unroute('**/api/next')
    await page.getByRole('button', { name: 'Reconnect' }).click()
    await page.route('**/api/next', async route => { await new Promise(resolve => setTimeout(resolve, 300))
      await route.continue() })
    await page.getByRole('button', { name: 'Next write' }).click()
    await page.getByRole('status').waitFor()
    await page.getByText('Capture a project note', { exact: true }).waitFor()
    results.push({ width, height, overflow, undersized, approval: true, rejection: true, keyboardTabs: true, errorRecovery: true, loading: true, darkTheme: true })
    await page.close()
  }
  writeFileSync('docs/console/evidence/browser.json', JSON.stringify(results, null, 2) + '\n')
} finally { await browser.close() }
